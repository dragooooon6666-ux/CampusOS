def main():
    passed = 0
    print(f"{'文件名':<38} {'分类结果':<10} {'置信':<7} {'判定依据':<20} 结果")
    print("-" * 100)
    for filename, expected, note in CASES:
        r = classify(filename)
        ok = r.doc_type == expected
        if ok:
            passed += 1
        short = filename if len(filename) <= 36 else filename[:34] + ".."
        mark = "OK" if ok else f"X  期望:{expected}"
        flag = "" if ok else f"  <- {note}"
        print(f"{short:<38} {r.doc_type:<10} {r.confidence:<7} {r.reason:<20} {mark}{flag}")

    total = len(CASES)
    print("-" * 100)
    print(f"通过 {passed}/{total}  ({passed * 100 // total}%)")


if __name__ == "__main__":
    main()
